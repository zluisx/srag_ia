CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) UNIQUE NOT NULL, senha VARCHAR(100) NOT NULL,
  perfil VARCHAR(12) NOT NULL CHECK (perfil IN ('OPERADOR','GESTOR'))
);
CREATE TABLE IF NOT EXISTS casos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id), entrada VARCHAR(2000) NOT NULL,
  excluido BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS predicoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  caso_id BIGINT NOT NULL REFERENCES casos(id), usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  entrada VARCHAR(2000) NOT NULL, resultado VARCHAR(4000) NOT NULL,
  faixa VARCHAR(10) NOT NULL, versao VARCHAR(60) NOT NULL,
  instante TIMESTAMP WITH TIME ZONE NOT NULL, revisao BOOLEAN DEFAULT FALSE NOT NULL
);
